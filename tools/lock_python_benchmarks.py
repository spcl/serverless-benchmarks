#!/usr/bin/env -S uv run --script
# /// script
# requires-python = ">=3.10"
# dependencies = ["tomlkit"]
# ///
"""Sync and re-lock the Python dependencies of every benchmark.

The deployment extras in each benchmark's pyproject.toml are generated from the
`modules` of its config.json and the `module_packages` in configs/systems.json.

    tools/lock_python_benchmarks.py            # sync pyproject.toml and re-lock
    tools/lock_python_benchmarks.py --upgrade  # also upgrade all packages within their specs
    tools/lock_python_benchmarks.py --check    # fail if a pyproject.toml or lockfile is stale (CI)
"""

import argparse
import json
import subprocess
import sys
from pathlib import Path

import tomlkit

ROOT = Path(__file__).resolve().parent.parent
SYSTEMS = json.loads((ROOT / "configs" / "systems.json").read_text())
MODULE_PACKAGES = {
    deployment: config["languages"]["python"]["deployment"]["module_packages"]
    for deployment, config in sorted(SYSTEMS.items())
    if "python" in config.get("languages", {})
}
# Functions only run on Linux; skip resolving for other platforms.
ENVIRONMENTS = ["sys_platform == 'linux'"]


def sync(pyproject: Path) -> str:
    """Return the pyproject.toml with generated deployment extras and uv environments."""
    doc = tomlkit.parse(pyproject.read_text())
    modules = json.loads((pyproject.parent.parent / "config.json").read_text())["modules"]

    extras = tomlkit.table()
    extras.comment("generated by tools/lock_python_benchmarks.py")
    for deployment, packages in MODULE_PACKAGES.items():
        extras[deployment] = [p for module in modules for p in packages.get(module, [])]
    doc["project"]["optional-dependencies"] = extras
    doc.setdefault("tool", tomlkit.table()).setdefault("uv", tomlkit.table())[
        "environments"
    ] = ENVIRONMENTS

    return tomlkit.dumps(doc)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--upgrade", action="store_true", help="upgrade all packages")
    mode.add_argument("--check", action="store_true", help="only verify that files are current")
    args = parser.parse_args()

    extra = ["--check"] if args.check else ["--upgrade"] if args.upgrade else []
    failed = []
    for pyproject in sorted(ROOT.glob("benchmarks/[0-9]*/*/python/pyproject.toml")):
        name = str(pyproject.parent.parent.relative_to(ROOT / "benchmarks"))
        print(name, flush=True)
        synced = sync(pyproject)
        if synced != pyproject.read_text():
            if args.check:
                print(f"{name}: pyproject.toml is out of sync", file=sys.stderr)
                failed.append(name)
                continue
            pyproject.write_text(synced)
        result = subprocess.run(["uv", "lock", "--quiet", *extra], cwd=pyproject.parent)
        if result.returncode != 0:
            failed.append(name)

    if failed:
        print("failed: " + ", ".join(failed), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
