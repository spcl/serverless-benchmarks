#!/usr/bin/env -S uv run python
"""Lock the Node.js dependencies of every benchmark for every deployment.

Every Node.js source directory of a benchmark, i.e., `nodejs/` and each variant
directory with its own package.json, gets one lockfile per deployment:
`package-lock.<deployment>.json` locks the package.json with the deployment packages
of configs/systems.json merged in (see sebs/dependencies.py).

Lockfiles are generated by the npm version pinned below, independent of the local
Node.js installation. Checking them needs neither npm nor network access.

    uv run tools/lock_nodejs_benchmarks.py            # lock new and changed dependencies
    uv run tools/lock_nodejs_benchmarks.py --upgrade  # also upgrade all packages within ranges
    uv run tools/lock_nodejs_benchmarks.py --check    # fail if a lockfile is stale (CI)
"""

import argparse
import json
import shutil
import subprocess
import sys
import tempfile
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path
from typing import NamedTuple

from sebs import dependencies
from sebs.config import SeBSConfig

ROOT = Path(__file__).resolve().parent.parent
NPM = "npm@11.20.0"


class Job(NamedTuple):
    """One package.json and the lockfile generated from it."""

    name: str
    package_json: dict
    lockfile: Path

    def is_current(self) -> bool:
        """Check that the lockfile exists and was generated from the package.json."""
        return dependencies.nodejs_lockfile_is_current(str(self.lockfile), self.package_json)


def npm(*args: str, cwd: Path) -> None:
    """Run the pinned npm version."""
    subprocess.run(
        ["npx", "--yes", NPM, *args], cwd=cwd, check=True, capture_output=True, text=True
    )


def lock(job: Job, upgrade: bool) -> str:
    """Return the lockfile of a job, reusing the locked versions unless upgrading."""
    with tempfile.TemporaryDirectory() as tmp:
        # npm records the directory name in the lockfile; keep it stable.
        work = Path(tmp) / "function"
        work.mkdir()
        (work / "package.json").write_text(json.dumps(job.package_json, indent=2))
        if job.lockfile.exists() and not upgrade:
            shutil.copy(job.lockfile, work / "package-lock.json")
        npm(
            "install",
            "--package-lock-only",
            "--ignore-scripts",
            "--no-audit",
            "--no-fund",
            cwd=work,
        )
        return (work / "package-lock.json").read_text()


def benchmark_jobs(config: SeBSConfig) -> list[Job]:
    """Return the lockfiles of all benchmarks for all deployments."""
    jobs = []
    for language_dir in sorted(ROOT.glob("benchmarks/[0-9]*/*/nodejs")):
        modules = json.loads((language_dir.parent / "config.json").read_text())["modules"]
        for source in map(Path, dependencies.nodejs_sources(str(language_dir))):
            package_json = json.loads((source / "package.json").read_text())
            for deployment in config.deployments("nodejs"):
                jobs.append(
                    Job(
                        f"{source.relative_to(ROOT / 'benchmarks')} ({deployment})",
                        dependencies.nodejs_package_json(package_json, config, deployment, modules),
                        Path(dependencies.nodejs_lockfile(str(source), deployment)),
                    )
                )
    return jobs


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--upgrade", action="store_true", help="upgrade all packages")
    mode.add_argument("--check", action="store_true", help="only verify that lockfiles are current")
    args = parser.parse_args()

    jobs = benchmark_jobs(SeBSConfig())
    expected = {job.lockfile for job in jobs}
    orphaned = sorted(
        lockfile
        for lockfile in ROOT.glob("benchmarks/[0-9]*/*/nodejs/**/package-lock.*.json")
        if lockfile not in expected
    )

    if args.check:
        failed = [job.name for job in jobs if not job.is_current()]
        failed += [str(lockfile.relative_to(ROOT)) for lockfile in orphaned]
        for name in failed:
            print(f"{name}: lockfile is missing, stale, or orphaned", file=sys.stderr)
        return 1 if failed else 0

    for lockfile in orphaned:
        print(f"removing {lockfile.relative_to(ROOT)}")
        lockfile.unlink()

    def run(job: Job) -> bool:
        try:
            job.lockfile.write_text(lock(job, args.upgrade))
            print(job.name)
            return True
        except subprocess.CalledProcessError as e:
            print(f"{job.name}: npm failed:\n{e.stderr}", file=sys.stderr)
            return False

    stale = [job for job in jobs if args.upgrade or not job.is_current()]
    if stale:
        # Fetch the pinned npm once, before the parallel jobs share the npx cache.
        npm("--version", cwd=ROOT)
    # npm spends most of its time waiting on the registry; lock in parallel.
    with ThreadPoolExecutor(max_workers=8) as pool:
        failed = [job.name for job, ok in zip(stale, pool.map(run, stale)) if not ok]
    if failed:
        print("failed: " + ", ".join(failed), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
